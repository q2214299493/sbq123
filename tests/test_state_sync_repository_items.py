def _cleanup(tmp_path: Path, *, disposition: str = "delete", approve: bool = True):
    policy, schema = init_repository(tmp_path)
    source = tmp_path / "scratch/cache.txt"
    source.parent.mkdir()
    source.write_bytes(b"original\n")
    event = build_stale_item_event(
        project_root=tmp_path,
        path=source,
        disposition=disposition,
        content_class="unique" if disposition == "archive" else "regenerable",
        reason="Review one exact repository file.",
        schema_path=schema,
    )
    event_store = store(tmp_path, schema)
    event_store.record(event)
    proposal = build_proposal(event, project_root=tmp_path, policy_path=policy)
    cache = ProposalStore(tmp_path, policy)
    cache.save(proposal)
    if approve:
        event_store.record_review(
            proposal_id=proposal["proposal_id"],
            decision="approve",
            reviewer="user",
            reviewed_event_id=event.event_id,
            reviewed_event_sha256=event.digest,
        )
    return policy, schema, source, event, event_store, proposal, cache


def _sync(tmp_path: Path, policy: Path, schema: Path, capsys, *, safe_only: bool = True):
    arguments = ["--root", str(tmp_path), "--policy", str(policy), "--schema", str(schema), "sync"]
    if safe_only:
        arguments.append("--safe-only")
    result = main(
        arguments
    )
    return result, json.loads(capsys.readouterr().out)


@pytest.mark.parametrize("approve", [False, True])
@pytest.mark.parametrize("disposition", ["keep", "archive", "delete"])
def test_safe_sync_defers_repository_classifications(tmp_path, capsys, approve, disposition):
    policy, schema, source, event, event_store, _, cache = _cleanup(
        tmp_path, disposition=disposition, approve=approve
    )
    events_before = list(event_store.load_all())
    result, output = _sync(tmp_path, policy, schema, capsys)

    assert result == 0
    assert source.read_bytes() == b"original\n"
    assert output["applied"] == output["pending_review"] == []
    assert output["deferred_repository_items"] == [
        {
            "event_id": event.event_id,
            "event_sha256": event.digest,
            "reason": "One-time repository operations require explicit reviewed apply.",
        }
    ]
    assert list(event_store.load_all()) == events_before
    assert not (cache.cache_dir / "applications").exists()


@pytest.mark.parametrize("regenerated", [b"original\n", b"regenerated by a later build\n"])
@pytest.mark.parametrize("safe_only", [False, True])
def test_legacy_cleanup_does_not_replay_or_block_later_projection(tmp_path, capsys, regenerated, safe_only):
    policy, schema, source, cleanup, event_store, _, cache = _cleanup(tmp_path)
    # Legacy cleanups predate application receipts. Represent the completed
    # deletion, then a later build recreating the same path with either hash.
    source.unlink()
    source.write_bytes(regenerated)
    assert not (cache.cache_dir / "applications").exists()

    evidence = tmp_path / "task-evidence.txt"
    evidence.write_text("Reviewed task evidence.\n", encoding="utf-8")
    payload = task_event("zz-task-after-cleanup", evidence=file_evidence(evidence, tmp_path)).payload
    payload["recorded_at"] = cleanup.payload["recorded_at"]
    task = StateEvent.from_mapping(payload, schema_path=schema)
    current_task = tmp_path / "tasks/current_task.md"
    current_task.write_text(
        START_MARKER.format(block_id="current_task")
        + "\n# Current Task\n\nOld\n"
        + END_MARKER.format(block_id="current_task") + "\n",
        encoding="utf-8",
    )
    event_store.record(task)

    result, output = _sync(tmp_path, policy, schema, capsys, safe_only=safe_only)
    assert result == 0
    assert "tasks/current_task.md" in output["applied"]
    assert task.payload["payload"]["objective"] in current_task.read_text(encoding="utf-8")
    assert source.read_bytes() == regenerated
    assert output["pending_review"] == []
    assert [item["event_id"] for item in output["deferred_repository_items"]] == [cleanup.event_id]

    result, repeated = _sync(tmp_path, policy, schema, capsys, safe_only=safe_only)
    assert result == 0
    assert repeated["applied"] == []
    assert repeated["deferred_repository_items"] == output["deferred_repository_items"]
    assert source.read_bytes() == regenerated


def test_safe_sync_defers_approved_batch_move(tmp_path, capsys):
    policy, schema = init_repository(tmp_path)
    source = tmp_path / ".codex_tmp/job/CONTCAR"
    source.parent.mkdir(parents=True)
    source.write_bytes(b"unique scientific fixture\n")
    destination = tmp_path / "calculations/recovered/job/CONTCAR"
    manifest = tmp_path / "cleanup.json"
    manifest.write_text(json.dumps({
        "schema_version": 1,
        "document_kind": "repository_cleanup_manifest",
        "bundle_id": "deferred-batch-move",
        "reason": "Review one exact move.",
        "items": [{
            "path": source.relative_to(tmp_path).as_posix(),
            "target_path": destination.relative_to(tmp_path).as_posix(),
            "disposition": "move",
            "content_class": "unique",
            "reason": "Preserve the unique fixture.",
        }],
    }), encoding="utf-8")
    event = build_stale_item_batch_event(project_root=tmp_path, manifest_path=manifest, schema_path=schema)
    event_store = store(tmp_path, schema)
    event_store.record(event)
    proposal = build_proposal(event, project_root=tmp_path, policy_path=policy)
    event_store.record_review(
        proposal_id=proposal["proposal_id"], decision="approve", reviewer="user",
        reviewed_event_id=event.event_id, reviewed_event_sha256=event.digest,
    )

    result, output = _sync(tmp_path, policy, schema, capsys)
    assert result == 0
    assert source.read_bytes() == b"unique scientific fixture\n"
    assert not destination.exists()
    assert output["applied"] == []
    assert output["deferred_repository_items"][0]["event_id"] == event.event_id


def test_explicit_apply_still_rejects_changed_cleanup_source(tmp_path):
    policy, _, source, _, event_store, proposal, _ = _cleanup(tmp_path)
    source.write_bytes(b"new content must be preserved\n")

    with pytest.raises(ValueError, match="evidence hash changed"):
        apply_proposal(proposal, event_store=event_store, project_root=tmp_path, policy_path=policy)
    assert source.read_bytes() == b"new content must be preserved\n"


@pytest.mark.parametrize("safe_only", [False, True])
def test_cleanup_only_sync_preserves_and_reports_unknown_application_lock(tmp_path, safe_only):
    policy, schema, source, _, event_store, _, cache = _cleanup(tmp_path)
    lock = cache.cache_dir / "application.lock"
    unknown = b'{"status":"UNKNOWN_NEEDS_RECONCILIATION"}\n'
    lock.write_bytes(unknown)
    events_before = list(event_store.load_all())

    command = [
        sys.executable, "-m", "scripts.state_manager", "--root", str(tmp_path),
        "--policy", str(policy), "--schema", str(schema), "sync",
    ]
    if safe_only:
        command.append("--safe-only")
    result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True)
    assert result.returncode != 0
    assert "UNKNOWN_NEEDS_RECONCILIATION; never automatically retry" in result.stderr
    assert result.stdout == ""
    assert lock.read_bytes() == unknown
    assert source.read_bytes() == b"original\n"
    assert list(event_store.load_all()) == events_before
    assert not (cache.cache_dir / "applications").exists()
